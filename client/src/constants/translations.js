// Helper function to get translation
export const getTranslation = (path, language = "id") => {
  const keys = path.split(".");
  let value = translations;

  for (const key of keys) {
    value = value[key];
    if (!value) return path; // Return path if translation not found
  }

  return value[language] || value["id"] || path;
};

// Hook for easier translation usage
export const useTranslation = (language) => {
  return (path) => getTranslation(path, language);
};
